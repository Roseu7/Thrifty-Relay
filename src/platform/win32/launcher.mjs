import fs from "node:fs/promises";
import path from "node:path";
import { CREDENTIAL_TARGET } from "./secrets.mjs";

// The launcher is the one file Task Scheduler starts, so it is also the file the local
// management tools read: scripts/mcp-control.mjs parses the $tunnel, $mcpCommand and
// $healthAddress lines out of it. Keep those three lines in this exact shape (one assignment
// per line, double quoted) or mcp:check stops being able to verify the running process tree.
export function launcherPath({ env = process.env } = {}) {
  const localAppData = env.LOCALAPPDATA;
  if (typeof localAppData !== "string" || !localAppData) {
    throw Object.assign(new Error("LAUNCHER_PATH_UNAVAILABLE"), { code: "LAUNCHER_PATH_UNAVAILABLE" });
  }
  return path.win32.join(localAppData, "ThriftyRelay", "Start-ThriftyRelay.ps1");
}

// The launcher writes one log next to its own directory. Uninstall removes that file and
// only the directories it owns; unrelated files under ThriftyRelay are left alone.
export function launcherLogPath({ env = process.env } = {}) {
  return path.win32.join(path.win32.dirname(launcherPath({ env })), "logs", "remote.log");
}

// Double quoted so mcp-control's regex reads the value; PowerShell still expands $ and ` inside.
function psDouble(value) {
  return '"' + String(value).replaceAll("`", "``").replaceAll('"', '`"').replaceAll("$", "`$") + '"';
}

// The credential is read natively instead of through a PowerShell gallery module: an
// installation that needs a third party module installed first is not an installation the MCP
// can depend on, and the target is the same store the setup CLI writes (secrets.mjs).
const CREDENTIAL_READER = String.raw`
$credentialSignature = @'
using System;
using System.Runtime.InteropServices;
using System.Text;
public static class ThriftyRelayLauncherCredential {
  [StructLayout(LayoutKind.Sequential)] public struct FileTime { public uint Low; public uint High; }
  [StructLayout(LayoutKind.Sequential, CharSet=CharSet.Unicode)] public struct Credential {
    public uint Flags;
    public uint Type;
    public string TargetName;
    public string Comment;
    public FileTime LastWritten;
    public uint CredentialBlobSize;
    public IntPtr CredentialBlob;
    public uint Persist;
    public uint AttributeCount;
    public IntPtr Attributes;
    public string TargetAlias;
    public string UserName;
  }
  [DllImport("advapi32.dll", EntryPoint="CredReadW", CharSet=CharSet.Unicode, SetLastError=true)]
  public static extern bool CredRead(string target, uint type, uint flags, out IntPtr credential);
  [DllImport("advapi32.dll", EntryPoint="CredFree")]
  public static extern void CredFree(IntPtr credential);
}
'@
$null = Add-Type -TypeDefinition $credentialSignature
$credentialPointer = [IntPtr]::Zero
if (-not [ThriftyRelayLauncherCredential]::CredRead($credentialTarget, 1, 0, [ref]$credentialPointer)) {
  throw "Credential '$credentialTarget' not found"
}
try {
  $stored = [Runtime.InteropServices.Marshal]::PtrToStructure(
    $credentialPointer, [type][ThriftyRelayLauncherCredential+Credential])
  if ($stored.CredentialBlobSize -le 0 -or $stored.CredentialBlobSize -gt 2560 -or
      ($stored.CredentialBlobSize % 2) -ne 0) {
    throw "Credential '$credentialTarget' is invalid"
  }
  $blob = New-Object byte[] ([int]$stored.CredentialBlobSize)
  [Runtime.InteropServices.Marshal]::Copy($stored.CredentialBlob, $blob, 0, $blob.Length)
  $secret = [Text.Encoding]::Unicode.GetString($blob)
  [Array]::Clear($blob, 0, $blob.Length)
} finally {
  [ThriftyRelayLauncherCredential]::CredFree($credentialPointer)
}
if ([string]::IsNullOrWhiteSpace($secret)) {
  throw "Credential '$credentialTarget' contains no password"
}
`;

export function launcherScript({
  tunnel,
  tunnelId,
  mcpCommand,
  healthAddress = "127.0.0.1:8080",
  credentialTarget = CREDENTIAL_TARGET,
  taskDirectory,
  codexWorkspace,
  tempWorkspace,
}) {
  for (const [name, value] of Object.entries({ tunnel, tunnelId, mcpCommand, credentialTarget, taskDirectory })) {
    if (typeof value !== "string" || !value) throw Object.assign(new Error("LAUNCHER_CONFIG_INVALID"), {
      code: "LAUNCHER_CONFIG_INVALID", detail: name,
    });
  }
  return `$ErrorActionPreference = "Stop"

# ============================================================
# ThriftyRelay launcher (generated by setup; edit through setup)
# ============================================================

# --- Paths ---
$logDir = Join-Path $env:LOCALAPPDATA "ThriftyRelay\\logs"
$logFile = Join-Path $logDir "remote.log"

$tunnel = ${psDouble(tunnel)}

# --- Tunnel settings ---
$tunnelId = ${psDouble(tunnelId)}
$credentialTarget = ${psDouble(credentialTarget)}

# --- MCP server command ---
$mcpCommand = ${psDouble(mcpCommand)}

# --- Health endpoint ---
$healthAddress = ${psDouble(healthAddress)}

# ============================================================
# Logging
# ============================================================

New-Item -ItemType Directory -Force -Path $logDir | Out-Null

function Write-Log {
    param([Parameter(Mandatory = $true)][string]$Message)
    $line = "[$(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')] $Message"
    $line | Out-File -FilePath $logFile -Append -Encoding utf8
}

# ============================================================
# Start
# ============================================================

$launcherMutex = $null
$launcherMutexHeld = $false
$secret = $null

try {
    Write-Log "ThriftyRelay starting"

    # Prevent duplicate launches from the scheduled task and manual runs.
    $launcherMutex = New-Object System.Threading.Mutex($false, 'Local\\ThriftyRelayLauncher')
    $launcherMutexHeld = $launcherMutex.WaitOne(0)
    if (-not $launcherMutexHeld) {
        Write-Log "Another launcher is active; duplicate start skipped"
        exit 0
    }

    # A tunnel process may outlive its launcher (for example, after closing a terminal).
    $tunnelName = [IO.Path]::GetFileName($tunnel)
    $existingTunnel = @(Get-CimInstance Win32_Process |
        Where-Object { $_.Name -ieq $tunnelName -and $_.ExecutablePath -ieq $tunnel })
    if ($existingTunnel.Count -gt 0) {
        $existingPids = @($existingTunnel | ForEach-Object { $_.ProcessId })
        $existingListener = @(Get-NetTCPConnection -LocalPort 8080 -State Listen -ErrorAction SilentlyContinue |
            Where-Object { $_.OwningProcess -in $existingPids })
        if ($existingListener.Count -gt 0) {
            Write-Log "Tunnel already listening on 8080 (PID: $($existingListener[0].OwningProcess)); duplicate start skipped"
            exit 0
        }
        throw "Tunnel process exists but is not listening on 8080 (PID: $($existingPids -join ', ')); refusing duplicate start"
    }

    $portListener = @(Get-NetTCPConnection -LocalPort 8080 -State Listen -ErrorAction SilentlyContinue)
    if ($portListener.Count -gt 0) {
        throw "Port 8080 already in use by PID $($portListener[0].OwningProcess); refusing duplicate start"
    }

${CREDENTIAL_READER}
    # --------------------------------------------------------
    # Environment variables used by tunnel-client
    # --------------------------------------------------------

    $env:CONTROL_PLANE_API_KEY = $secret
    $env:CONTROL_PLANE_TUNNEL_ID = $tunnelId

    $env:THRIFTYRELAY_TASK_DIR = ${psDouble(taskDirectory)}
    $env:THRIFTYRELAY_CODEX_WORKSPACE = ${psDouble(codexWorkspace || taskDirectory)}
    $env:THRIFTYRELAY_TEMP_WORKSPACE = ${psDouble(tempWorkspace || "")}

    # --------------------------------------------------------
    # Check tunnel-client
    # --------------------------------------------------------

    if (-not (Test-Path -LiteralPath $tunnel)) {
        throw "tunnel-client not found: $tunnel"
    }

    Write-Log "Starting tunnel-client"

    # ProcessStartInfo is used instead of Start-Process because Start-Process can drop the
    # quotes around --mcp.command and pass its words to tunnel-client instead.
    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = $tunnel
    $psi.Arguments = ('run ' +
        '--mcp.command "' + $mcpCommand + '" ' +
        '--health.listen-addr "' + $healthAddress + '"')
    $psi.UseShellExecute = $false
    $psi.CreateNoWindow = $true
    $psi.WindowStyle = [System.Diagnostics.ProcessWindowStyle]::Hidden
    $psi.RedirectStandardError = $true

    $process = New-Object System.Diagnostics.Process
    $process.StartInfo = $psi

    if (-not $process.Start()) {
        throw "Failed to start tunnel-client"
    }

    Write-Log "tunnel-client started (PID: $($process.Id))"

    while (-not $process.HasExited) {
        $line = $process.StandardError.ReadLine()
        if ($null -ne $line) {
            $line | Out-File -FilePath $logFile -Append -Encoding utf8
        }
    }

    $remainingError = $process.StandardError.ReadToEnd()
    if (-not [string]::IsNullOrWhiteSpace($remainingError)) {
        $remainingError | Out-File -FilePath $logFile -Append -Encoding utf8
    }

    $process.WaitForExit()
    Write-Log "tunnel-client exited with code $($process.ExitCode)"
    exit $process.ExitCode
}
catch {
    Write-Log "ERROR: $($_.Exception.Message)"
    exit 1
}
finally {
    if ($launcherMutexHeld) {
        $launcherMutex.ReleaseMutex() | Out-Null
    }
    if ($null -ne $launcherMutex) {
        $launcherMutex.Dispose()
    }
    Remove-Item Env:CONTROL_PLANE_API_KEY -ErrorAction SilentlyContinue
    Remove-Item Env:CONTROL_PLANE_TUNNEL_ID -ErrorAction SilentlyContinue
    $secret = $null
}
`;
}

// A replace, so a half written launcher is never what the scheduled task starts.
export async function writeLauncher({ file = launcherPath(), content }) {
  const directory = path.dirname(file);
  await fs.mkdir(directory, { recursive: true });
  const temporary = path.join(directory, `.launcher-${process.pid}-${Date.now()}.tmp`);
  try {
    await fs.writeFile(temporary, content, { encoding: "utf8", flag: "wx", mode: 0o644 });
    await fs.rename(temporary, file);
  } finally {
    await fs.rm(temporary, { force: true }).catch(() => {});
  }
  return file;
}
